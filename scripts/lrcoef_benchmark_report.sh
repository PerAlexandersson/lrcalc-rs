#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UPSTREAM_LIB="${UPSTREAM_LIB:-/tmp/lrcalc-upstream/src/.libs/liblrcalc.so}"
OUTPUT="${1:-notes/LRCOEF_BENCHMARK_REPORT.md}"

if [[ ! -f "$UPSTREAM_LIB" ]]; then
  cat >&2 <<EOF
upstream shared library not found:
  $UPSTREAM_LIB

Build it first:
  cd /tmp/lrcalc-upstream
  autoreconf -i
  ./configure --enable-shared --disable-static
  make -j2
EOF
  exit 2
fi

cd "$ROOT_DIR"

emit_report() {
  local git_rev
  local git_full_rev
  local git_state
  git_rev="$(git rev-parse --short HEAD)"
  git_full_rev="$(git rev-parse HEAD)"
  if [[ -z "$(git status --porcelain)" ]]; then
    git_state="clean"
  else
    git_state="dirty"
  fi

  echo "# LR/Kostka Benchmark Report"
  echo
  echo "- Generated by: \`scripts/lrcoef_benchmark_report.sh\`"
  echo "- Git revision: \`$git_rev\`"
  echo "- Full revision: \`$git_full_rev\`"
  echo "- Working tree at run time: \`$git_state\`"
  echo "- Upstream library: \`$UPSTREAM_LIB\`"
  echo "- LR FFI template: \`timeout 60s nice -n 10 cargo run --release --bin lrcoef_ffi_bench -- --markdown <repeat> <suite>\`"
  echo "- Kostka template: \`timeout 60s nice -n 10 cargo run --release --bin kostka_bench -- --markdown <repeat>\`"
  echo "- Stretched LR template: \`timeout 60s nice -n 10 cargo run --release --bin lr_hstar_bench -- --markdown <repeat> <stretch>\`"
  echo
  echo "The LR FFI suites check Rust results against upstream C before timing. Ratios"
  echo "there are \`Rust/C\`, so values below \`1.000x\` mean the Rust ABI path is"
  echo "faster. The non-FFI sections compare Rust algorithm choices directly."
  echo
  echo "## Automatic Detection Notes"
  echo
  echo "- The hybrid full/interior LR counter automatically detects exact"
  echo "  Kostka-translation shapes; the stretched DP table reports this as"
  echo "  \`Hybrid mode = kostka\`."
  echo "- Generic stretched LR/Ehrhart evaluation is explicit, not automatic in"
  echo "  \`lrcoef_i64\`. The current explicit path computes an h*-polynomial and"
  echo "  then evaluates cached h* data at the requested stretch."
  echo "- A future ABI heuristic can detect a common dilation factor, divide to the"
  echo "  primitive triple, estimate the dimension, and use h* evaluation only when"
  echo "  the stretch is large enough to repay interpolation."
  echo

  run_suite 5000 mixed
  echo
  run_suite 10000 large-few-parts
  echo
  run_suite 1000 large-three-part
  echo
  run_kostka_suite 1000
  echo
  run_stretched_dp_suite 5 3
  echo
  run_lr_hstar_suite 3 5
}

run_suite() {
  local repeat="$1"
  local suite="$2"
  UPSTREAM_LIB="$UPSTREAM_LIB" \
    timeout 60s nice -n 10 cargo run --release --bin lrcoef_ffi_bench -- \
      --markdown "$repeat" "$suite"
}

run_kostka_suite() {
  local repeat="$1"
  timeout 60s nice -n 10 cargo run --release --bin kostka_bench -- \
    --markdown "$repeat"
}

run_stretched_dp_suite() {
  local repeat="$1"
  local max_scale="$2"
  timeout 60s nice -n 10 cargo run --release --bin stretched_dp_bench -- \
    --markdown "$repeat" "$max_scale"
}

run_lr_hstar_suite() {
  local repeat="$1"
  local stretch="$2"
  timeout 60s nice -n 10 cargo run --release --bin lr_hstar_bench -- \
    --markdown "$repeat" "$stretch"
}

if [[ "$OUTPUT" == "-" ]]; then
  emit_report
else
  TMP_OUTPUT="$(mktemp)"
  trap 'rm -f "$TMP_OUTPUT"' EXIT
  mkdir -p "$(dirname "$OUTPUT")"
  emit_report > "$TMP_OUTPUT"
  mv "$TMP_OUTPUT" "$OUTPUT"
  trap - EXIT
  echo "wrote $OUTPUT"
fi
