#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UPSTREAM_LIB="${UPSTREAM_LIB:-/tmp/lrcalc-upstream/src/.libs/liblrcalc.so}"
OUTPUT="${1:-notes/LRCOEF_BENCHMARK_REPORT.md}"

if [[ ! -f "$UPSTREAM_LIB" ]]; then
  cat >&2 <<EOF
upstream shared library not found:
  $UPSTREAM_LIB

Build it first:
  cd /tmp/lrcalc-upstream
  autoreconf -i
  ./configure --enable-shared --disable-static
  make -j2
EOF
  exit 2
fi

cd "$ROOT_DIR"

emit_report() {
  local git_rev
  local git_full_rev
  local git_state
  git_rev="$(git rev-parse --short HEAD)"
  git_full_rev="$(git rev-parse HEAD)"
  if [[ -z "$(git status --porcelain)" ]]; then
    git_state="clean"
  else
    git_state="dirty"
  fi

  echo "# LR Coefficient FFI Benchmark Report"
  echo
  echo "- Generated by: \`scripts/lrcoef_benchmark_report.sh\`"
  echo "- Git revision: \`$git_rev\`"
  echo "- Full revision: \`$git_full_rev\`"
  echo "- Working tree at run time: \`$git_state\`"
  echo "- Upstream library: \`$UPSTREAM_LIB\`"
  echo "- Benchmark command template: \`timeout 60s nice -n 10 cargo run --release --bin lrcoef_ffi_bench -- --markdown <repeat> <suite>\`"
  echo
  echo "Each suite checks Rust results against upstream C before timing. Ratios are"
  echo "\`Rust/C\`, so values below \`1.000x\` mean the Rust ABI path is faster."
  echo

  run_suite 5000 mixed
  echo
  run_suite 10000 large-few-parts
  echo
  run_suite 1000 large-three-part
}

run_suite() {
  local repeat="$1"
  local suite="$2"
  UPSTREAM_LIB="$UPSTREAM_LIB" \
    timeout 60s nice -n 10 cargo run --release --bin lrcoef_ffi_bench -- \
      --markdown "$repeat" "$suite"
}

if [[ "$OUTPUT" == "-" ]]; then
  emit_report
else
  TMP_OUTPUT="$(mktemp)"
  trap 'rm -f "$TMP_OUTPUT"' EXIT
  mkdir -p "$(dirname "$OUTPUT")"
  emit_report > "$TMP_OUTPUT"
  mv "$TMP_OUTPUT" "$OUTPUT"
  trap - EXIT
  echo "wrote $OUTPUT"
fi
